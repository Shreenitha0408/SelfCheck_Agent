"""Descriptive statistics for the prepared splits (written to reports/)."""

from __future__ import annotations

from collections import Counter
from statistics import mean, median
from typing import Any

from .schema import Document, Example


def _dist(values: list[Any]) -> dict[str, float]:
    c = Counter(str(v) for v in values)
    n = len(values) or 1
    return {k: round(v / n, 3) for k, v in sorted(c.items())}


def split_stats(examples: list[Example], corpus: dict[str, Document]) -> dict[str, Any]:
    n = len(examples)
    ans = [e for e in examples if e.answerable and not e.ambiguous]
    doc_lens = [len(corpus[d].text.split()) for e in examples for d in e.scope_doc_ids]
    s: dict[str, Any] = {
        "n": n,
        "answerable_frac": round(sum(e.answerable for e in examples) / n, 3) if n else 0,
        "ambiguous_frac": round(sum(e.ambiguous for e in examples) / n, 3) if n else 0,
        "answer_type": _dist([e.answer_type for e in examples]),
        "question_words_mean": round(mean(len(e.question.split()) for e in examples), 1),
        "scope_docs_mean": round(mean(len(e.scope_doc_ids) for e in examples), 1),
        "scope_docs_max": max(len(e.scope_doc_ids) for e in examples),
        "doc_words_median": median(doc_lens) if doc_lens else 0,
        "gold_docs_mean_answerable": round(mean(len(e.gold_doc_ids) for e in ans), 2) if ans else 0,
        "answerable_with_text_evidence_frac": round(
            sum(bool(e.gold_doc_ids) for e in ans) / len(ans), 3
        )
        if ans
        else 0,
        "with_gold_steps_frac": round(sum(bool(e.steps) for e in examples) / n, 3) if n else 0,
    }
    if examples and "hops" in examples[0].meta:
        s["hops"] = _dist([e.meta["hops"] for e in examples])
    if examples and "hotpot_type" in examples[0].meta:
        s["hotpot_type"] = _dist([e.meta["hotpot_type"] for e in examples])
        s["hotpot_level"] = _dist([e.meta["hotpot_level"] for e in examples])
    if examples and "paper_id" in examples[0].meta:
        s["papers"] = len({e.meta["paper_id"] for e in examples})
    return s


ROWS = [
    ("n", "Questions"),
    ("answerable_frac", "Answerable"),
    ("ambiguous_frac", "Ambiguous"),
    ("answer_type", "Answer type"),
    ("hops", "Hops"),
    ("hotpot_type", "HotpotQA type"),
    ("hotpot_level", "HotpotQA level"),
    ("papers", "Distinct papers"),
    ("question_words_mean", "Question length (words, mean)"),
    ("scope_docs_mean", "Passages per question (mean)"),
    ("scope_docs_max", "Passages per question (max)"),
    ("doc_words_median", "Passage length (words, median)"),
    ("gold_docs_mean_answerable", "Gold evidence passages (mean, answerable)"),
    ("answerable_with_text_evidence_frac", "Answerable Qs with text evidence"),
    ("with_gold_steps_frac", "Has gold step decomposition"),
]


PERCENT_KEYS = {k for k, _ in ROWS if k.endswith("_frac")}


def _fmt(v: Any, key: str = "") -> str:
    if isinstance(v, dict):
        return ", ".join(f"{k}: {x:.0%}" for k, x in v.items())
    if key in PERCENT_KEYS and isinstance(v, (int, float)):
        return f"{v:.1%}"
    return str(v)


def to_markdown(all_stats: dict[str, dict[str, dict[str, Any]]], pool_sizes: dict[str, int]) -> str:
    out = ["# Dataset statistics", "", "Generated by `scripts/prepare_data.py`. "
           "`pool` = all usable questions in the source eval split; "
           "`dev` = threshold tuning only; `test` = held-out reporting set.", ""]
    for ds, splits in all_stats.items():
        out += [f"## {ds}", "", f"Source pool: {pool_sizes[ds]} questions", "",
                "| | " + " | ".join(splits) + " |", "|---|" + "---|" * len(splits)]
        for key, label in ROWS:
            if any(key in s for s in splits.values()):
                out.append(f"| {label} | " + " | ".join(_fmt(s.get(key, ""), key) for s in splits.values()) + " |")
        out.append("")
    return "\n".join(out)
